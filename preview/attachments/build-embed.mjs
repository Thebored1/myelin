#!/usr/bin/env node
// Regenerate attachments/_files.js from the real attachment files.
//
// The mockup fetches the .md/.json/.log/.csv files directly when it is served
// over http. Chromium blocks fetch() on file://, so the same bytes are also
// embedded as a classic script. The files on disk stay the source of truth;
// this file is a build artefact of them.
//
//   node preview/attachments/build-embed.mjs

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const names = (await readdir(here))
	.filter((n) => !n.startsWith('_') && !n.endsWith('.mjs'))
	.sort();

const out = [
	'// GENERATED by build-embed.mjs - do not edit.',
	'// Source of truth is the attachment files next to this one.',
	'window.MYELIN_FILES = {'
];

for (const name of names) {
	const body = await readFile(join(here, name), 'utf8');
	out.push(`\t${JSON.stringify(name)}: ${JSON.stringify(body)},`);
}

out.push('};', '');
await writeFile(join(here, '_files.js'), out.join('\n'));
console.log(`_files.js: ${names.length} files, ${out.join('\n').length} bytes`);